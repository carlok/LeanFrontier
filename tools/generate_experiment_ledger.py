#!/usr/bin/env python3
"""Derive the launcher A/B assignment ledger from accepted submission claims.

The arm travels inside the submission claim rather than in a hand-kept file.
CONTRACT.md section 2 permits an ordinary submission to change only Lean source
and one `Submissions/*.json`, so a producer cannot append to a side ledger in
the same pull request, and a separate pull request races the first. Recording
the arm in the claim makes the assignment atomic with the submission it
describes; this file is the readable view of it.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DESTINATION = Path("experiments") / "launcher-ab.csv"

HEADER = """# GENERATED by tools/generate_experiment_ledger.py -- do not edit.
# Derived from the launcher_arm field of accepted submission claims.
# See PREREGISTRATION.md for the design this records.
#
# The starting arm was drawn once, before any assignment, from a fact fixed in
# advance:
#   seed = int(sha256(b"5f7d730").hexdigest()[:8], 16) = 590768208
#   random.Random(seed).choice(["A", "B"]) -> "A"
# where 5f7d730 is the merge commit of the pre-registration itself. Assignment
# alternates thereafter: A B A B ...
#
# Submissions carrying no launcher_arm predate the experiment or arrived
# unprompted; they are recorded as unassigned and belong to neither arm.
submission_id,arm,producer_model
"""


def rows(root: Path) -> list[tuple[str, str, str]]:
    result: list[tuple[str, str, str]] = []
    for path in sorted((root / "Submissions").glob("*.json")):
        claim = json.loads(path.read_text(encoding="utf-8"))
        producer = claim.get("producer") or {}
        result.append((
            str(claim.get("submission_id", path.stem)),
            str(claim.get("launcher_arm") or "unassigned"),
            str(producer.get("model") or "unrecorded"),
        ))
    return result


def render(root: Path) -> str:
    return HEADER + "".join(",".join(row) + "\n" for row in rows(root))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = args.root / DESTINATION
    expected = render(args.root)
    existing = destination.read_text(encoding="utf-8") if destination.exists() else ""
    if expected == existing:
        return 0
    if args.check:
        print(f"{destination} is stale; run tools/generate_experiment_ledger.py")
        return 1
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
